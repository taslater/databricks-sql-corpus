def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    jobs = [
        ("SqlBaseLexer.g4", patch_lexer),
        ("SqlBaseParser.g4", patch_parser),
    ]
    for name, fn in jobs:
        src = VENDOR_DIR / name
        if not src.exists():
            print(f"error: {src} missing -- run scripts/fetch_grammar.py first", file=sys.stderr)
            return 1
        try:
            patched = fn(src.read_text())
        except PatchError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        dest = OUT_DIR / name
        dest.write_text(patched)
        print(f"patched {name} -> {dest.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
